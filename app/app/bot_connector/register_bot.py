import argparse
import yaml
import subprocess
import uuid

def load_yaml(path):
    with open(path, 'r') as f:
        return yaml.safe_load(f) or {}

def generate_insert_sql(botname, entry, password_hash):
    return f"""
DELETE FROM users WHERE username = '{botname}';
INSERT INTO users (
  username, display_name, user_type, email, password, api_key,
  must_change_password, account_balance, initial_account_balance,
  personal_emoji, description, personal_link1, personal_link2, personal_link3, personal_link4,
  created_at, updated_at
) VALUES (
  '{botname}', '{botname}', 'REGULAR', '{botname}@example.com',
  '{password_hash}', '{entry['api_key']}', false, 0, 0,
  '🤖', 'Autogenerated dev bot user',
  '', '', '', '',
  now(), now()
);
"""

def cmd_register_db(args):
    bots = load_yaml(args.yaml)
    password = args.password.encode('utf-8')

    import bcrypt
    hashed = bcrypt.hashpw(password, bcrypt.gensalt()).decode()

    for botname, entry in bots.items():
        if not entry.get("api_key"):
            entry["api_key"] = str(uuid.uuid4())
        sql = generate_insert_sql(botname, entry, hashed)

        result = subprocess.run([
            "docker", "exec", "-i", args.container,
            "psql", "-U", args.db_user, "-d", args.db_name
        ], input=sql.encode(), capture_output=True)

        if result.returncode != 0:
            print(f"❌ Failed for {botname}:\n{result.stderr.decode()}")
        else:
            print(f"✅ Inserted {botname}")

def main():
    parser = argparse.ArgumentParser(description="Register bots into SocialPredict DB")
    parser.add_argument('--yaml', required=True, help="Path to bots.yaml")
    parser.add_argument('--password', default="password")
    parser.add_argument('--container', default="socialpredict-postgres-container")
    parser.add_argument('--db-user', default="user")
    parser.add_argument('--db-name', default="socialpredict_db")
    parser.set_defaults(func=cmd_register_db)
    args = parser.parse_args()
    args.func(args)

if __name__ == "__main__":
    main()
